create or replace function public.increment_site_visit()
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_value bigint;
begin
  insert into public.site_stats (key, value, updated_at)
  values ('site_visits', 1, now())
  on conflict (key)
  do update set
    value = public.site_stats.value + 1,
    updated_at = now()
  returning value into new_value;

  return new_value;
end;
$$;

grant execute on function public.increment_site_visit() to anon, authenticated;

create or replace function public.increment_quote_view(quote_id bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_value bigint;
begin
  update public.quotes
  set view_count = view_count + 1
  where id = quote_id
  returning view_count into new_value;

  return coalesce(new_value, 0);
end;
$$;

grant execute on function public.increment_quote_view(bigint) to anon, authenticated;

