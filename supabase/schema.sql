create or replace function public.refresh_quote_comment_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  quote_ids bigint[];
begin
  if TG_OP = 'INSERT' then
    quote_ids := array[NEW.quote_id];
  elsif TG_OP = 'DELETE' then
    quote_ids := array[OLD.quote_id];
  else
    quote_ids := array[OLD.quote_id, NEW.quote_id];
  end if;

  update public.quotes as quote
  set comment_count = (
    select count(*)
    from public.comments as comment
    where comment.quote_id = quote.id
  )
  where quote.id = any(quote_ids);

  return coalesce(NEW, OLD);
end;
$$;

drop trigger if exists refresh_quote_comment_count_on_change on public.comments;
create trigger refresh_quote_comment_count_on_change
after insert or update or delete on public.comments
for each row
execute function public.refresh_quote_comment_count();

